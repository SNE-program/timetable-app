function go(id: string): void {
  const el = document.getElementById('doc-' + id);
  if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

/**
 * 把字符串里的 **强调** 渲染成加粗。
 *
 * 说明书正文大多是普通字符串（不是 JSX），而写作时习惯用 `**` 标重点 ——
 * 不转换的话，用户在说明书里看到的是一堆裸星号。凡是"整段文字当字符串传进来"的
 * 地方（P / UL / Steps / Note / QA）都过一遍这个函数。
 * 传进来的已经是 JSX 节点时原样返回。
 */
function rich(text: React.ReactNode): React.ReactNode {
  if (typeof text !== 'string' || text.indexOf('**') < 0) return text;
  const parts = text.split('**');
  return parts.map(function (seg, i) {
    return i % 2 === 1 ? <b key={i}>{seg}</b> : <React.Fragment key={i}>{seg}</React.Fragment>;
  });
}

function H(props: { children: React.ReactNode }) {
  return <div className="doc-h3">{rich(props.children)}</div>;
}

function P(props: { children: React.ReactNode }) {
  return <div className="doc-p">{rich(props.children)}</div>;
}

function UL(props: { items: React.ReactNode[] }) {
  return (
    <ul className="doc-ul">
      {props.items.map(function (it, i) { return <li key={i}>{rich(it)}</li>; })}
    </ul>
  );
}

function Steps(props: { items: { t: string; d: React.ReactNode }[] }) {
  return (
    <div className="doc-steps">
      {props.items.map(function (s, i) {
        return (
          <div className="doc-step" key={i}>
            <span className="doc-step-n">{i + 1}</span>
            <div>
              <div className="doc-step-t">{rich(s.t)}</div>
              <div className="doc-step-d">{rich(s.d)}</div>
            </div>
          </div>
        );
      })}
    </div>
  );
}

function Note(props: { children: React.ReactNode }) {
  return <div className="doc-note">{rich(props.children)}</div>;
}

function QA(props: { q: string; children: React.ReactNode }) {
  return (
    <div className="doc-qa">
      <div className="doc-q">{rich(props.q)}</div>
      <div className="doc-a">{rich(props.children)}</div>
    </div>
  );
}

