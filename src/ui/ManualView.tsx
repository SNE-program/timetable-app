/**
 * 把"整本说明书"的 JSX 拆成一个个 section 节点。
 *
 * 说明书正文是一大段字面量 JSX（每一章一个 <section id="doc-xxx">），
 * 这里不重写正文，只在渲染时挑出当前这一章 —— 于是正文一个字都不用动，
 * 而 DOM 从 790 个节点降到几十个。
 */
function sectionsOf(body: React.ReactNode): React.ReactNode[] {
  const kids = (body as React.ReactElement<{ children?: React.ReactNode }>).props.children;
  return React.Children.toArray(kids);
}
