/**
 * 更新日志（应用内展示）。
 *
 * ## 这里放什么
 *
 * 从 1.0.0 起，**应用内的更新日志是给用户看的发行说明**：
 * 每条都说清「你能感知到什么变化」，不写实现细节、不提内部参数与调试入口。
 *
 * 完整的技术记录仍然留在仓库里，两者分工明确：
 *
 *   - `CHANGELOG.md`  —— 逐版本的完整记录（含验证数据、交付信息），给维护者看
 *   - `docs/`         —— 每个专题的工程笔记，给维护者看
 *   - 本文件          —— 应用内「设置 → 关于 → 更新日志」渲染的发行说明，给用户看
 *
 * ## 写新条目的约定
 *
 *   1. 在数组最前面插入一条，`version` 与 `package.json` 保持一致；
 *   2. `kind` 只用 new / fix / opt / note 四种（新增 / 修复 / 优化 / 说明）；
 *   3. 一句话说清"用户能感知到什么"，别写"重构了某某模块"；
 *   4. 不要出现调试参数、内部选择器、单测数量、打包与版本号之类的过程信息；
 *   5. 涉及不可逆操作（删除、清空、覆盖）时，明确写出来。
 */

export type ChangeKind = 'new' | 'fix' | 'opt' | 'note';

export interface ChangeItem {
  kind: ChangeKind;
  text: string;
}

export interface ChangeEntry {
  version: string;
  /** 发布日期；早期版本没有留档，留空表示不显示日期 */
  date: string;
  title: string;
  /** 这一版是否需要在界面上重点提示（默认不提示） */
  items: ChangeItem[];
}

